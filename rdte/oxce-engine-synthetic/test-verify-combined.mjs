#!/usr/bin/env node
// Offline non-native orchestrator tests. Test doubles never qualify real OXCE.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { verify } from './verify-combined.mjs';

function setup(t,{drift=false,missing=false,retail=false,exitFailure=false}={}){
 const base=fs.mkdtempSync(path.join(os.tmpdir(),'sf-combined-stub-'));
 t.after(()=>fs.rmSync(base,{recursive:true,force:true}));
 const scripts=path.join(base,'scripts');fs.mkdirSync(scripts);
 const write=(name,code)=>fs.writeFileSync(path.join(scripts,name),code);
 write('generate.mjs', `import fs from 'node:fs';import path from 'node:path';
  const root=process.argv[2];const put=(p,s)=>{p=path.join(root,p);fs.mkdirSync(path.dirname(p),{recursive:true});fs.writeFileSync(p,s)};
  put('config/options.cfg','mods: test');put('user/mods/rdte-synthetic-master/metadata.yml','id: rdte-synthetic-master');
  put('user/mods/rdte-synthetic-master/Ruleset/10-synthetic.rul','terrains: test');
  put('user/mods/rdte-synthetic-master/Language/en-US.yml','en-US: test');
 `);
 write('generate-font.mjs',`import fs from 'node:fs';import path from 'node:path';const root=path.join(process.argv[2],'user/mods/rdte-synthetic-master/Language');fs.mkdirSync(root,{recursive:true});fs.writeFileSync(path.join(root,'rdte-fonts.yml'),'fonts: test');fs.writeFileSync(path.join(root,'rdte-fonts.png'),Buffer.from('synthetic'))`);
 write('generate-legacy.mjs',`import fs from 'node:fs';import path from 'node:path';const root=process.argv[2];const put=(p,s)=>{p=path.join(root,p);fs.mkdirSync(path.dirname(p),{recursive:true});fs.writeFileSync(p,s)};
  put('rdte/synthetic-legacy-manifest.json','{}');
  ${missing?'':"put('MAPS/SFREL00.MAP','MAP');"}
  put('ROUTES/SFREL00.RMP','RMP');put('TERRAIN/BLANKS.MCD','MCD');
  ${retail?"put('../UFO/retail.bin','INVALID');":''}
  for(let i=0;i<76;i++)put('SOUND/f'+i+'.wav',${drift?'Math.random().toString()':"'synthetic'"});
 `);
 for(const name of ['test-generated-master.mjs','test-generated-font.mjs','test-stock-spawn-prerequisites.mjs','test-generated-legacy.mjs'])write(name,exitFailure&&name==='test-generated-font.mjs'?'process.exit(7);':'console.log("PASS");');
 return {scripts,base};
}

test('two independent original-only roots reproduce byte-for-byte',async t=>{
 const {scripts,base}=setup(t);const r=await verify({workdir:base,scriptsDir:scripts});
 assert.equal(r.result,'PASS');assert.equal(r.replay,'BYTE_IDENTICAL');assert.ok(r.files>=80);
 assert.equal(r.nativeOXCE,'NOT_RUN');assert.equal(r.selectedSignalFrontierGame,'NOT_RUN');
 assert.equal(r.tests.length,7);assert.equal(r.runBTests.length,6);
});
test('independent replay detects nondeterministic generated bytes',async t=>{
 const {scripts,base}=setup(t,{drift:true});await assert.rejects(verify({workdir:base,scriptsDir:scripts}),/generated original fixture differs/);
});
test('missing native resource is a hard failure',async t=>{
 const {scripts,base}=setup(t,{missing:true});await assert.rejects(verify({workdir:base,scriptsDir:scripts}),/missing integrated output/);
});
test('unexpected commercial game path is a hard failure',async t=>{
 const {scripts,base}=setup(t,{retail:true});await assert.rejects(verify({workdir:base,scriptsDir:scripts}),/commercial game path/);
});
test('first generator/regression failure is preserved',async t=>{
 const {scripts,base}=setup(t,{exitFailure:true});await assert.rejects(verify({workdir:base,scriptsDir:scripts}),/test-generated-font\.mjs: exit=7/);
});
